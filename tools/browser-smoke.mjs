// Optional development tool. Runtime and unit tests require no installed packages.
// PLAYWRIGHT_MODULE can point to an existing playwright(-core)/index.mjs.
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const baseURL = process.env.BASE_URL || 'http://127.0.0.1:4174';
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
const results = [], errors = [], externalRequests = [];
await mkdir('artifacts', { recursive: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
page.on('pageerror', e => errors.push(e.message));
page.on('request', r => { if (new URL(r.url()).origin !== new URL(baseURL).origin && !r.url().startsWith('data:')) externalRequests.push(r.url()); });
const readSave = () => page.evaluate(() => JSON.parse(localStorage.getItem('ntk-codex-vertical-v1')));
const run = ms => page.clock.runFor(ms);
const click = name => page.getByRole('button', { name, exact: true }).click();
try {
  await page.clock.install();
  await page.goto(baseURL);
  await page.getByRole('heading', { name: '説明は、 必要な分だけ。' }).waitFor();
  await page.screenshot({ path: 'artifacts/title-desktop.png', fullPage: true });
  await click('被験者として入る →');
  await click('C-04 に入室 →');
  await page.keyboard.down('d'); await run(11000); await page.keyboard.up('d');
  assert.ok((await readSave()).trial.x >= 22);
  await page.keyboard.press('e'); await run(40);
  assert.equal((await readSave()).trial.hasBox, true);
  await page.screenshot({ path: 'artifacts/trial-desktop.png', fullPage: true });
  await page.getByRole('button', { name: '断る' }).click();
  await page.keyboard.down('Alt'); await page.keyboard.down('a'); await run(22000);
  await page.keyboard.up('a'); await page.keyboard.up('Alt'); await run(20);
  await page.keyboard.press('e'); await run(20);
  assert.equal((await readSave()).phase, 'debrief');
  assert.equal((await readSave()).subject.suspicion, 0);
  await click('「足音が聞こえたので、止まりました。」');
  await click('居住区へ戻る →');
  await page.locator('.checklist input').first().check();
  await click('選んだ記録を封筒へ');
  assert.equal((await readSave()).envelope.length, 1);
  await click('安全な整理業務を手伝う');
  assert.equal((await readSave()).subject.credit, 1);
  await click('消灯・今回の検証を終える →');
  assert.equal((await readSave()).phase, 'complete');
  results.push('UI: enter, move, retrieve box, refuse order, slow return, interview, report, envelope, safe duty, complete');

  await click('同じ初期条件で新規開始');
  assert.equal((await readSave()).reports.length, 1);
  await click('C-04 に入室 →');
  await page.keyboard.down('Shift'); await page.keyboard.down('d'); await run(1000);
  await page.keyboard.up('d'); await page.keyboard.up('Shift');
  await page.keyboard.press('Escape');
  const paused = await readSave();
  assert.equal(paused.trial.mode, 'approaching');
  await run(5000); assert.deepEqual(await readSave(), paused);
  await page.screenshot({ path: 'artifacts/paused-warning.png', fullPage: true });
  await page.reload();
  await click('記録から再開 →');
  assert.deepEqual(await readSave(), paused);
  await run(2000); assert.deepEqual(await readSave(), paused);
  await click('操作を再開 →');
  await run(700); assert.equal((await readSave()).trial.mode, 'retreating');
  await page.getByRole('tab', { name: '仮説' }).click();
  const beforeNotes = await readSave();
  await page.getByRole('textbox', { name: '仮説の自由記入' }).fill('仮説：停止の後に足音が遠のいた。');
  await run(2000); assert.equal((await readSave()).trial.elapsed, beforeNotes.trial.elapsed);
  await click('仮説を記録する');
  assert.equal((await readSave()).subject.suspicion, 0);
  assert.equal((await readSave()).subject.hypotheses.length, 1);
  results.push('UI: warning, pause freezes all clocks, reload restores exact warning, resumes paused, note entry pauses and does not add suspicion');

  // Check all three output settings against the same visible warning event.
  await page.getByRole('checkbox', { name: '音の字幕', exact: true }).uncheck();
  await page.locator('#volume').fill('0');
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(() => document.activeElement.id), 'scene');
  await page.keyboard.down('Shift'); await page.keyboard.down('d'); await run(150);
  assert.match(await page.locator('#visual-cue').textContent(), /背後で重なる/);
  await page.keyboard.up('d'); await page.keyboard.up('Shift'); await page.keyboard.press('Escape');
  await page.getByRole('checkbox', { name: '音の字幕', exact: true }).check();
  await click('操作を再開 →');
  await page.keyboard.down('Shift'); await page.keyboard.down('d'); await run(3100);
  await page.keyboard.up('d'); await page.keyboard.up('Shift');
  assert.equal((await readSave()).phase, 'death');
  await click('翌日・次の被験者へ →');
  assert.equal((await readSave()).day, 2);
  assert.equal((await readSave()).subject.id, 'D-9342');
  assert.equal((await readSave()).subject.hypotheses.length, 0);
  assert.equal((await readSave()).reports.length, 2);
  results.push('UI: visual warning remains with subtitles off and volume zero; death changes subject/day once, preserves report archive');

  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'artifacts/mobile-layout.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(() => {
    for(const e of document.querySelectorAll('h1,h2,h3,p,button,label,.eyebrow')) e.style.fontSize=`${parseFloat(getComputedStyle(e).fontSize)*2}px`;
  });
  await page.screenshot({ path: 'artifacts/text-200.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const entry = page.getByRole('button', { name: 'C-04 に入室 →', exact: true });
  await entry.scrollIntoViewIfNeeded();
  const entryBox = await entry.boundingBox(), overlayBox = await page.locator('#overlay').boundingBox();
  assert.ok(entryBox.y >= overlayBox.y && entryBox.y + entryBox.height <= overlayBox.y + overlayBox.height);
  results.push('Layout: no page horizontal overflow at 390px and desktop with 200% text; entry button remains scroll-reachable');

  const corruptContext = await browser.newContext();
  const corruptPage = await corruptContext.newPage();
  await corruptPage.addInitScript(() => { localStorage.setItem('ntk-codex-vertical-v1', '{broken-fixture'); });
  await corruptPage.goto(baseURL);
  await corruptPage.getByRole('alert').waitFor();
  await corruptPage.getByRole('button', { name: '被験者として入る →' }).click();
  assert.equal(await corruptPage.evaluate(() => localStorage.getItem('ntk-codex-vertical-v1')), '{broken-fixture');
  await corruptPage.screenshot({ path: 'artifacts/corrupt-save.png', fullPage: true });
  results.push('Recovery: corrupt save produces warning and is not overwritten by new-game button');
  await corruptContext.close();
  assert.deepEqual(errors, []); assert.deepEqual(externalRequests, []);
  results.push('No uncaught page errors or external requests');
  const report = { status: 'PASS', at: new Date().toISOString(), browser: browser.version(), clock: 'synthetic browser clock; not human playtime', results, errors, externalRequests };
  await writeFile('artifacts/browser-verification.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }
